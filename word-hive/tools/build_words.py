#!/usr/bin/env python3
"""Build word-hive/words.js from the SCOWL word lists.

Usage (from the repo root):
    cd /tmp && npm pack wordlist-english && tar xzf wordlist-english-*.tgz
    python3 word-hive/tools/build_words.py /tmp/package

Output: word-hive/words.js, defining WORDS (accepted answers) and PUZZLES
(7-letter sets, centre letter first).
"""
import json
import random
import re
import sys
from pathlib import Path

ACCEPT_TIERS = (10, 20, 35)   # answers the game accepts: common-ish English
PANGRAM_TIERS = (10, 20)      # the "use every letter" word must be very common
MIN_ANSWERS, MAX_ANSWERS = 20, 60

# Keep it family friendly: drop words starting with these, except ALLOW.
BLOCK_PREFIXES = [
    "anal", "bitch", "booby", "booze", "bugger", "butt", "cocaine", "cock", "crap",
    "damn", "drug", "drunk", "erotic", "fagg", "hell", "heroin", "homophob", "horny",
    "kill", "murder", "naked", "nincompoop", "nude", "overkill", "pimp", "poop",
    "prick", "queer", "rape", "rebutt", "retard", "titillat", "vagin", "whore",
]
ALLOW = {
    "analogue", "analogy", "analytic", "analytical", "butte", "butter", "buttercup",
    "buttered", "buttery", "button", "buttoned", "buttoning", "cockpit", "cockroach",
    "cocktail", "hello", "heroine", "prickle", "pricklier", "prickly",
}


def load(src, tiers):
    words = set()
    for t in tiers:
        words |= set(json.loads((src / f"english-words-{t}.json").read_text()))
    return words


def usable(w):
    # 4+ letters, no S (avoids cheap plurals), at most 7 distinct letters.
    if not re.fullmatch(r"[a-z]{4,}", w) or "s" in w or len(set(w)) > 7:
        return False
    return w in ALLOW or not any(w.startswith(p) for p in BLOCK_PREFIXES)


def main(src):
    words = sorted(w for w in load(src, ACCEPT_TIERS) if usable(w))
    common = load(src, PANGRAM_TIERS)
    letter_sets = {frozenset(w) for w in words if len(set(w)) == 7 and w in common}

    puzzles = []
    for letters in letter_sets:
        fits = [w for w in words if set(w) <= letters]
        for centre in sorted(letters):
            n = sum(centre in w for w in fits)
            if MIN_ANSWERS <= n <= MAX_ANSWERS:
                puzzles.append(centre + "".join(sorted(letters - {centre})))
    puzzles.sort()
    random.Random(7).shuffle(puzzles)

    out = Path(__file__).resolve().parent.parent / "words.js"
    out.write_text(
        "// Generated by tools/build_words.py from SCOWL (see WORDLIST-COPYRIGHT.txt).\n"
        f"const WORDS = {json.dumps(' '.join(words))};\n"
        f"const PUZZLES = {json.dumps(' '.join(puzzles))};\n"
    )
    print(f"{len(words)} words, {len(puzzles)} puzzles -> {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
